import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const out = process.argv[2] ?? 'screens';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
page.on('pageerror', (e) => console.log('PAGE ERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.click('button.tab:has-text("Compare")');
await page.waitForTimeout(300);
await page.evaluate(`window.__sim.setTarget(24, 18); window.__sim.stepSeconds(90 + 30 * 60); window.__sim.setTarget(5, 9); window.__sim.stepSeconds(5 * 60);`);
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/compare.png`, fullPage: true });
await page.click('button.tab:has-text("Lessons")');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/lessons.png` });
await page.click('.lesson-card >> nth=3');
await page.waitForTimeout(400);
await page.evaluate(`window.__sim.setTarget(30, 18); window.__sim.stepSeconds(100 + 22 * 60);`);
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/lesson-deco.png` });
await page.click('button.tab:has-text("Reference")');
await page.waitForTimeout(500);
await page.click('.docs .chip >> nth=4');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/reference.png` });
await page.click('button.tab:has-text("About")');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/about.png` });
await browser.close();
console.log('done');
