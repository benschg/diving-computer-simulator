import { chromium } from 'playwright';
const out = '/tmp/claude-1000/-workspaces-diving-computer-simulator/63eb4fa3-14be-4343-9a17-0f7911e26f99/scratchpad/screens';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
page.on('pageerror', (e) => console.log('PAGE ERROR', e.message));
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.selectOption('select', 'garmin-descent-g1');
await page.waitForTimeout(200);
await page.evaluate(`window.__sim.setTarget(24, 18); window.__sim.stepSeconds(90 + 20 * 60);`);
await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/garmin-ndl.png` });
await page.evaluate(`window.__sim.stepSeconds(12 * 60); window.__sim.setTarget(5, 9); window.__sim.stepSeconds(2 * 60 + 30);`);
await page.waitForTimeout(200);
await page.screenshot({ path: `${out}/garmin-safety.png` });
await page.click('button.tab:has-text("Present")');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/present.png` });
await page.click('button.tab:has-text("Exit presentation")');
await page.selectOption('select >> nth=0', 'suunto-zoop-novo');
await page.waitForTimeout(200);
await page.selectOption('select[aria-label="Play a scripted scenario"]', 'Fast ascent from 20 m');
await page.waitForTimeout(1500);
await page.evaluate(`window.__sim.pause()`);
await page.screenshot({ path: `${out}/scenario.png` });
await browser.close();
console.log('done');
